def get_glyph(char):
    """Вернуть глиф символа или заглушку для неизвестного символа."""
    return FONT.get(char, EMPTY_GLYPH)


def text_width(text, scale):
    """Вычислить ширину текста в пикселях с учётом масштаба."""
    if not text:
        return 0
    return len(text) * GLYPH_STEP * scale - scale
